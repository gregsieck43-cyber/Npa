import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';
import { startBackend } from '../src/app/backend.js';
import { ExternalTools } from '../src/app/external-tools.js';
import { WebError } from '../src/network/index.js';
import type { ToolDetailPage } from '../src/frontend/api/types.js';

/**
 * Real Runner -> Kernel failure -> WorkTrace -> authenticated Bridge/HTTP. Search attempts are
 * generated by production WebClient from injected failing transports, never fabricated in SQLite.
 * There is no public socket or paid model. SearchAttempt records durationMs, not an absolute time;
 * the enclosing real Kernel/Trace event supplies the invocation timestamp.
 */
test('ToolDetail result preserves every generated search attempt across paging, catch-up and restart', { timeout: 35000 }, async t => {
  const root = path.resolve(process.env.TEMP ?? '.tmp/tool-retry-history-20261104'); mkdirSync(root, { recursive: true });
  const owned = mkdtempSync(path.join(root, 'tool-retry-')), dataDir = path.join(owned, 'data');
  const workspace = path.join(owned, 'workspace'); mkdirSync(workspace);
  let modelCalls = 0;
  const options = { projectRoot: process.cwd(), dataDir, mockOptions: { responder: (body: any) => {
    modelCalls++;
    if (body.messages.some((message: any) => message.role === 'system' && String(message.content).includes('REVIEWER ROLE')))
      return { content: JSON.stringify({ verdict: 'pass', reason: 'Local read-only fixture', findings: [] }) };
    if (body.messages.some((message: any) => message.role === 'tool')) return { content: 'The local fixture sources failed; do not repeat.' };
    return { content: '', toolCalls: [{ id: 'search-attempt-history', name: 'web_search', arguments: { query: 'Synthetic retry history, no external transport' } }] };
  } } };
  let backend = await startBackend(options);
  const originalExternal = backend.services.external;
  const transportCalls: string[] = [];
  const failureMessages = { exa: 'First source transport diagnostic: ' + '甲'.repeat(4300), mwmbl: 'Second source transport diagnostic: ' + '乙'.repeat(4300) };
  const external = new ExternalTools({ projectRoot: process.cwd(), dataDir: path.join(owned, 'network'), webOptions: {
    searchProvider: 'auto', resolveDns: async () => [{ address: '93.184.216.34', family: 4 }],
    fetch: (async (input: RequestInfo | URL) => {
      const url = new URL(String(input)); transportCalls.push(url.hostname);
      if (url.hostname === 'mcp.exa.ai') throw new WebError('RATE_LIMITED', failureMessages.exa);
      if (url.hostname === 'api.mwmbl.org') throw new WebError('HTTP_FAILED', failureMessages.mwmbl);
      assert.fail('Unexpected transport destination: ' + url.href);
    }) as typeof fetch,
  } });
  // Same narrow executor injection as runner-network-diagnostics.test.ts. All production state
  // transitions, failure serialization and WorkTrace import remain real.
  const wiring = backend.services as unknown as { external: ExternalTools; runner: { external?: ExternalTools } };
  wiring.external = external; wiring.runner.external = external;
  t.after(async () => { await backend.close(); await external.close(); await originalExternal.close(); assert.equal(path.dirname(owned), root); rmSync(owned, { recursive: true, force: true }); });
  const created = backend.services.command({ commandId: randomUUID(), type: 'create_task', parameters: {
    workspace, objective: 'Inspect every failed search source without retrying the effect', permission: { mode: 'full-access', app: 'work' }, maxModelCalls: 8,
  } });
  const taskId = created.taskId!;
  const until = async <T>(read: () => T, ready: (value: T) => boolean): Promise<T> => {
    const deadline = Date.now() + 15000;
    for (;;) { const value = read(); if (ready(value)) return value; assert.ok(Date.now() < deadline, 'real task did not settle'); await new Promise(resolve => setTimeout(resolve, 20)); }
  };
  await until(() => backend.services.kernel.getTask(taskId), task => task?.status === 'waiting_input');
  const h = backend.services.harness!; h.workTrace.sync();
  const tool = h.store.toolCalls({ taskId }).find(call => call.toolCallId === 'search-attempt-history');
  assert.ok(tool?.intentId); assert.equal(tool.status, 'failed'); assert.equal(tool.failureStage, 'execution');
  const intent = backend.services.kernel.getIntent(tool.intentId)!;
  assert.equal(intent.state, 'failed'); assert.equal(intent.failure?.code, 'SEARCH_UNAVAILABLE');
  const attempts = intent.failure!.attempts as { provider: string; endpoint: string; status: string; results: number; durationMs: number; errorCode: string; error: string }[];
  assert.deepEqual(attempts.map(attempt => [attempt.provider, attempt.status, attempt.errorCode]), [['exa', 'error', 'RATE_LIMITED'], ['mwmbl', 'error', 'HTTP_FAILED']]);
  assert.equal(attempts[0]!.error, failureMessages.exa); assert.equal(attempts[1]!.error, failureMessages.mwmbl);
  for (const attempt of attempts) {
    assert.ok(Number.isFinite(attempt.durationMs) && attempt.durationMs >= 0); assert.equal(attempt.results, 0);
    assert.match(attempt.endpoint, /^https:\/\//); assert.equal('startedAt' in attempt, false); assert.equal('finishedAt' in attempt, false);
  }
  assert.deepEqual(transportCalls, ['mcp.exa.ai', 'api.mwmbl.org']);
  const failedEvent = backend.services.kernel.events(taskId).find(event => event.type === 'effect.failed')!;
  assert.ok(Number.isFinite(Date.parse(failedEvent.createdAt)), 'the real invocation has an absolute event timestamp');
  assert.deepEqual(failedEvent.payload.attempts, attempts);
  assert.deepEqual(JSON.parse(String(tool.result)).error.attempts, attempts);

  const bundle = await build({ entryPoints: ['src/frontend/api/bridge.ts'], bundle: true, write: false, platform: 'node', format: 'esm', logLevel: 'silent' });
  const bridgePath = path.join(owned, 'bridge.mjs'); writeFileSync(bridgePath, bundle.outputFiles![0]!.text);
  const { BridgeGateway } = await import(pathToFileURL(bridgePath).href);
  const paths: string[] = [];
  const gateway = new BridgeGateway({ request: async (method: string, route: string) => {
    paths.push(route);
    const response = await fetch(`http://127.0.0.1:${backend.port}${route}`, { method, headers: { Authorization: `Bearer ${backend.token}` } });
    const value = await response.json(); return response.ok ? value : { ...value, httpStatus: response.status };
  }, desktop: async () => assert.fail('No desktop effects') });
  const readAll = async () => {
    let text = '', offset = 0, pages = 0, hash: string | undefined;
    for (;;) {
      const page: ToolDetailPage = await gateway.inspector.toolDetail(taskId, tool.id, 'result', offset);
      assert.equal(page.available, true); assert.equal(page.offset, offset); assert.ok(page.text.length <= 6000);
      assert.equal(hash ?? page.sha256, page.sha256); hash = page.sha256; text += page.text; pages++;
      if (page.nextOffset === undefined) break; assert.ok(page.nextOffset > offset); offset = page.nextOffset; assert.ok(pages < 10);
    }
    assert.ok(pages > 1, 'the actual attempts straddle the 6000-character boundary');
    const value = JSON.parse(text); assert.equal(value.effect, 'failed'); assert.equal(value.executed, true);
    assert.equal(value.error.code, 'SEARCH_UNAVAILABLE'); assert.deepEqual(value.error.attempts, attempts);
    return { text, hash, pages };
  };
  const first = await readAll(); assert.equal(first.text, tool.result);
  const before = h.store.traces({ taskId }).events.length;
  h.store.setSetting('kernelCursor', 0); h.workTrace.sync();
  assert.equal(h.store.traces({ taskId }).events.length, before); assert.deepEqual(await readAll(), first);
  const callCount = modelCalls;
  await backend.close(); backend = await startBackend(options); await backend.services.runner.stop();
  backend.services.harness!.workTrace.sync();
  assert.deepEqual(await readAll(), first, 'a fresh backend reads the persisted attempt details exactly');
  assert.deepEqual(transportCalls, ['mcp.exa.ai', 'api.mwmbl.org']); assert.equal(modelCalls, callCount, 'inspection and restart do not redispatch a model or tool');
  assert.equal(paths.length, first.pages * 3);
  t.diagnostic(JSON.stringify({ syntheticTransportAttempts: transportCalls.length, publicNetworkRequests: 0, localMockModelCalls: modelCalls, paidCalls: 0,
    pagesPerRead: first.pages, httpReads: paths.length, resultCharacters: first.text.length, invocationTimestamp: failedEvent.createdAt,
    attemptFields: Object.keys(attempts[0]!).sort(), perAttemptAbsoluteTimestamps: false, restartPreserved: true }));
});
